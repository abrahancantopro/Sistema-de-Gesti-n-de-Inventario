    private void jBregistrar2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBregistrar2ActionPerformed
        // TODO add your handling code here:
    String nombre = jTnombre2.getText().trim();
        String apellido = jTapellido2.getText().trim();
        String telefono = jTtelefono2.getText().trim();
        String correo = jTcorreo2.getText().trim();
        String dni = jTdni2.getText().trim();
        String password = new String(jPassword2.getPassword()).trim();
        String rol = jCroles2.getSelectedItem().toString();

        if (nombre.isEmpty() || apellido.isEmpty() || telefono.isEmpty() ||
            correo.isEmpty() || dni.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }

        try (Connection con = Conexion.getConnection()) {
            if (con == null) {
                JOptionPane.showMessageDialog(this, "Error de conexión");
                return;
            }

            String sql = "INSERT INTO usuario (nombre, apellido, cargo, usuario, contrasena) VALUES (?, ?, ?, ?, ?)";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, nombre);
            ps.setString(2, apellido);
            ps.setString(3, rol); // tu campo 'cargo' puede ser el rol
            ps.setString(4, correo); // asumimos que 'usuario' es correo
            ps.setString(5, password);
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Usuario registrado correctamente");
            limpiarCampos();
            cargarTabla();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage());
        }

    }//GEN-LAST:event_jBregistrar2ActionPerformed


 private void cargarTabla() {
        modelo.setRowCount(0);
        try (Connection con = Conexion.getConnection()) {
            if (con == null) return;
            String sql = "SELECT nombre, apellido, cargo, usuario, contrasena FROM usuario";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                modelo.addRow(new Object[]{
                    rs.getString("nombre"),
                    rs.getString("apellido"),
                    "", // Telefono (no existe en la tabla registro)
                    rs.getString("usuario"), // lo mostramos como correo
                    "", // DNI (no existe)
                    rs.getString("contrasena"),
                    rs.getString("cargo") // Roles
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar tabla: " + e.getMessage());
        }
    }


    private void jBeliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBeliminarActionPerformed
        // TODO add your handling code here:
   String id = jTid.getText().trim();

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro para eliminar");
            return;
        }

        try {
            PreparedStatement ps = con.prepareStatement("DELETE FROM categoria WHERE id=?");
            ps.setInt(1, Integer.parseInt(id));
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Registro eliminado");
            limpiarCampos();
            cargarTabla();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
}
    
    }//GEN-LAST:event_jBeliminarActionPerformed

    private void jBregsitrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBregsitrarActionPerformed
        // TODO add your handling code here:
    String nombre = jTnombre.getText().trim();
    String cantidad = jTcantidad.getText().trim();
    String fecha = jTfecha.getText().trim();

    if (nombre.isEmpty() || cantidad.isEmpty() || fecha.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos");
        return;
    }

    try {
        int cantidadInt = Integer.parseInt(cantidad);

        // Convertir fecha de dd/MM/yyyy a java.sql.Date
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
        java.util.Date parsedDate = sdf.parse(fecha);
        java.sql.Date sqlDate = new java.sql.Date(parsedDate.getTime());

        PreparedStatement ps = con.prepareStatement(
            "INSERT INTO categoria (nombre, cantidad, fecha) VALUES (?, ?, ?)"
        );
        ps.setString(1, nombre);
        ps.setInt(2, cantidadInt);
        ps.setDate(3, sqlDate); // ponemos la fecha convertida

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Categoría registrada");
        limpiarCampos();
        cargarTabla(); // recargar tabla
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage());
    }

    }//GEN-LAST:event_jBregsitrarActionPerformed

    private void jBactualizar2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBactualizar2ActionPerformed
        // TODO add your handling code here:
        String id = jTid.getText().trim();
        String nombre = jTnombre.getText().trim();
        String cantidad = jTcantidad.getText().trim();
        String fecha = jTfecha.getText().trim();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Seleccione un registro para actualizar");
        return;
    }

    try {
        int cantidadInt = Integer.parseInt(cantidad);

        // Convertir fecha de dd/MM/yyyy a java.sql.Date
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
        java.util.Date parsedDate = sdf.parse(fecha); // parsea string
        java.sql.Date sqlDate = new java.sql.Date(parsedDate.getTime()); // convierte a java.sql.Date

        PreparedStatement ps = con.prepareStatement(
            "UPDATE categoria SET nombre=?, cantidad=?, fecha=? WHERE id=?"
        );
        ps.setString(1, nombre);
        ps.setInt(2, cantidadInt);
        ps.setDate(3, sqlDate);
        ps.setInt(4, Integer.parseInt(id));

        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Registro actualizado");
        limpiarCampos();
        cargarTabla();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
    }
    }//GEN-LAST:event_jBactualizar2ActionPerformed


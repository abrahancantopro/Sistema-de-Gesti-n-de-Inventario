    private void cargarTabla() {
    try {
        modelo.setRowCount(0); // limpiar tabla
        PreparedStatement ps = con.prepareStatement("SELECT * FROM categoria");
        ResultSet rs = ps.executeQuery();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy"); // formato deseado
        while (rs.next()) {
            Date fecha = rs.getDate("fecha"); // obtiene la fecha de la DB
            String fechaFormateada = (fecha != null) ? sdf.format(fecha) : "";
            modelo.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("nombre"),
                rs.getInt("cantidad"),
                fechaFormateada
            });
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al cargar datos: " + e.getMessage());
    }

    }
  
